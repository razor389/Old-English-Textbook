"""Render the complete glossary Markdown masters as retained LuaLaTeX sources.

This renderer does not invent entries or rebuild the editable masters from registers.
Run check_glossary_exports.py after compilation, then inspect every rendered page.
"""
from pathlib import Path
import hashlib
import json
import re

ROOT = Path(__file__).resolve().parents[1]
DOCUMENTS = (
    ("old-english", "Old English–English"),
    ("english", "English–Old English"),
)


def escape(text):
    substitutions = {"\\": r"\textbackslash{}", "&": r"\&", "%": r"\%",
                     "$": r"\$", "#": r"\#", "_": r"\_", "{": r"\{",
                     "}": r"\}", "~": r"\textasciitilde{}", "^": r"\textasciicircum{}"}
    return "".join(substitutions.get(c, c) for c in text)


def inline(text):
    parts = re.split(r"(\*\*[^*]+\*\*|(?<!\*)\*[^*\n]+\*(?!\*))", text)
    result = []
    for part in parts:
        if part.startswith("**") and part.endswith("**"):
            result.append(r"\textbf{" + escape(part[2:-2]) + "}")
        elif part.startswith("*") and part.endswith("*"):
            result.append(r"\emph{" + escape(part[1:-1]) + "}")
        else:
            result.append(escape(part))
    return "".join(result)


def blocks(text):
    for chunk in re.split(r"\n\s*\n", text.strip()):
        chunk = chunk.strip()
        if not chunk or chunk.startswith("<!--"):
            continue
        if chunk.startswith("# "):
            yield "title", chunk[2:]
        elif chunk.startswith("## "):
            yield "heading", chunk[3:]
        elif chunk.startswith("### "):
            yield "subheading", chunk[4:]
        else:
            yield "paragraph", " ".join(chunk.splitlines())


def main():
    destination = ROOT / "typesetting/glossaries"
    destination.mkdir(parents=True, exist_ok=True)
    records = []
    for stem, running in DOCUMENTS:
        # The OE entries are followed by a full-width appendix. Sequential
        # final columns avoid multicol balancing overflowing that last page.
        column_environment = "multicols*" if stem == "old-english" else "multicols"
        entry_skip = "3.8pt" if stem == "old-english" else "4pt"
        source = ROOT / "glossaries" / (stem + ".md")
        raw = source.read_text(encoding="utf-8-sig")
        events = list(blocks(raw))
        lines = [f"% Editable master: glossaries/{stem}.md",
                 "% Complete export; generated by scripts/build_glossary_exports.py.",
                 r"\newcommand{\runningtitle}{" + escape(running) + "}",
                 r"\input{../book-layout.tex}",
                 r"\usepackage{multicol}",
                 r"\raggedcolumns",
                 # Restore the preceding skip after the reservation. Leaving a
                 # negative final skip makes section spacing add the reservation
                 # back as visible whitespace.
                 r"\newcommand{\needspace}[1]{\par\begingroup\skip0=\lastskip\vskip-\skip0\dimen0=#1\relax\advance\dimen0 by\skip0\vskip0pt plus\dimen0\penalty-100\vskip0pt plus-\dimen0\vskip\dimen0\penalty9999\vskip-\dimen0\vskip\skip0\endgroup}",
                 r"\setlength{\columnsep}{6mm}",
                 r"\hyphenpenalty=10000\exhyphenpenalty=10000",
                 r"\emergencystretch=2em",
                 r"\begin{document}",
                 r"\addfontfeatures{Ligatures=TeXOff}",
                 r"\raggedright"]
        in_columns = False
        previous_kind = None
        for number, (kind, value) in enumerate(events, 1):
            block_id = f"B{number:05}"
            if kind == "heading" and value == "Quoted errors and reconstructions" and in_columns:
                lines += [r"\end{" + column_environment + "}", r"\clearpage"]
                in_columns = False
            if kind in ["title", "heading", "subheading"]:
                level = 1 if kind == "subheading" else 0
                lines.append(r"\pdfbookmark[" + str(level) + "]{" + escape(value) + "}{outline-" + block_id + "}")
            if kind == "heading" and value == "Entries":
                lines += [r"\clearpage", r"\fontsize{10.5}{13.2}\selectfont",
                          r"\setlength{\parskip}{" + entry_skip + "}", r"\begin{" + column_environment + "}{2}"]
                in_columns = True
            lines.append(f"% glossary-block:{block_id}:begin")
            if kind == "title":
                lines.append(r"\booktitle{GLOSSARY}{" + inline(value) + "}")
            elif kind == "heading":
                lines += [r"\needspace{5\baselineskip}", r"\section*{" + inline(value) + "}"]
            elif kind == "subheading":
                lines += [r"\needspace{5\baselineskip}", r"\subsection*{" + inline(value) + "}"]
            else:
                if in_columns and previous_kind not in ["heading", "subheading"]:
                    lines.append(r"\needspace{3\baselineskip}")
                lines.append(inline(value) + r"\par")
            lines.append(f"% glossary-block:{block_id}:end")
            if kind == "title" and stem == "old-english":
                # Match the reference-entry size so the complete usage guide
                # fits on one page without a mostly empty spill page.
                lines.append(r"\fontsize{10.5}{13.2}\selectfont")
            previous_kind = kind
        if in_columns:
            lines.append(r"\end{" + column_environment + "}")
        lines.append(r"\end{document}")
        target = destination / (stem + ".tex")
        target.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
        records.append({"id": stem, "master": source.relative_to(ROOT).as_posix(),
                        "tex": target.relative_to(ROOT).as_posix(),
                        "blocks": len(events), "master_sha256": hashlib.sha256(source.read_bytes()).hexdigest()})
    (destination / "content-map.json").write_text(
        json.dumps({"documents": records}, ensure_ascii=False, indent=2) + "\n",
        encoding="utf-8", newline="\n")
    print(json.dumps(records, ensure_ascii=False))


if __name__ == "__main__":
    main()
